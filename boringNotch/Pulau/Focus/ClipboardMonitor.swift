//  ClipboardMonitor.swift
//  boringNotch — Pulau fork
//
//  Text clipboard history, kept in memory only (never written to disk).
//  Skips items that password managers mark as concealed/transient.
//

import AppKit
import Combine
import Defaults
import Foundation

struct ClipboardEntry: Identifiable, Equatable {
    let id = UUID()
    let text: String
    let date: Date
    let sourceApp: String?

    var preview: String {
        let collapsed = text
            .replacingOccurrences(of: "\n", with: " ")
            .replacingOccurrences(of: "\t", with: " ")
            .trimmingCharacters(in: .whitespaces)
        return collapsed.count > 140 ? String(collapsed.prefix(140)) + "…" : collapsed
    }
}

@MainActor
final class ClipboardMonitor: ObservableObject {
    static let shared = ClipboardMonitor()

    @Published private(set) var entries: [ClipboardEntry] = []
    @Published private(set) var isRunning = false

    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: AnyCancellable?
    private var settingsObserver: AnyCancellable?

    /// See http://nspasteboard.org — markers used by 1Password, Bitwarden, Keychain, etc.
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "com.typeit4me.clipping",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type"
    ]

    private init() {
        lastChangeCount = NSPasteboard.general.changeCount
        settingsObserver = Defaults.publisher(.clipboardHistoryEnabled)
            .sink { [weak self] change in
                Task { @MainActor in
                    change.newValue ? self?.start() : self?.stop(clear: true)
                }
            }
    }

    func start() {
        guard !isRunning else { return }
        isRunning = true
        lastChangeCount = pasteboard.changeCount
        timer = Timer.publish(every: 0.6, on: .main, in: .common)
            .autoconnect()
            .sink { [weak self] _ in
                Task { @MainActor in self?.poll() }
            }
    }

    func stop(clear: Bool = false) {
        isRunning = false
        timer = nil
        if clear { entries.removeAll() }
    }

    func copy(_ entry: ClipboardEntry) {
        pasteboard.clearContents()
        pasteboard.setString(entry.text, forType: .string)
        // Move it to the top without duplicating.
        entries.removeAll { $0.text == entry.text }
        entries.insert(ClipboardEntry(text: entry.text, date: Date(), sourceApp: entry.sourceApp), at: 0)
        lastChangeCount = pasteboard.changeCount
    }

    func remove(_ entry: ClipboardEntry) {
        entries.removeAll { $0.id == entry.id }
    }

    func clear() {
        entries.removeAll()
    }

    /// Latest text on the clipboard (used by Assistant quick actions).
    var latestText: String? {
        pasteboard.string(forType: .string) ?? entries.first?.text
    }

    private func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count

        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }
        guard let text = pasteboard.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        // Very large blobs are not useful in a notch and cost memory.
        guard text.utf8.count <= 200_000 else { return }

        entries.removeAll { $0.text == text }
        let source = NSWorkspace.shared.frontmostApplication?.localizedName
        entries.insert(ClipboardEntry(text: text, date: Date(), sourceApp: source), at: 0)

        let limit = max(5, Defaults[.clipboardHistoryLimit])
        if entries.count > limit {
            entries.removeLast(entries.count - limit)
        }
    }
}
